-- Email тепер нормалізується (trim + lower-case) на вході (auth.schema.ts),
-- тож існуючі записи теж приводимо до нижнього регістру, інакше користувач
-- із "User@Mail.com" не зможе залогінитись (пошук іде по нормалізованому
-- значенню). Якщо в БД є два акаунти, що відрізняються лише регістром
-- email, міграція впаде на UNIQUE-обмеженні - такі дублікати треба
-- об'єднати/видалити вручну перед повторним запуском.
UPDATE "User"
SET "email" = lower(trim("email"))
WHERE "email" <> lower(trim("email"));
